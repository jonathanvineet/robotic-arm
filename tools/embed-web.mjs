// Packs web/ (gzip) into firmware/RoboArm/web_assets.h so the ESP serves the
// whole controller + digital twin from flash — no LittleFS upload step.
// Run after changing anything in web/:  npm run embed
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { join, relative, extname, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const web = join(root, 'web');
const MIME = { '.html': 'text/html', '.css': 'text/css', '.js': 'application/javascript', '.svg': 'image/svg+xml', '.json': 'application/json' };

const files = [];
(function walk(dir) {
  for (const n of readdirSync(dir)) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) {
      if (n !== 'tests') walk(p);
    } else if (MIME[extname(n)]) files.push(p);
  }
})(web);

let out = `// AUTO-GENERATED by tools/embed-web.mjs from web/ — do not edit.\n#pragma once\n#include <Arduino.h>\n\n`;
out += `struct WebAsset { const char* path; const char* mime; const uint8_t* data; size_t len; };\n\n`;
const table = [];
let total = 0;
files.sort().forEach((f, k) => {
  const gz = gzipSync(readFileSync(f), { level: 9 });
  total += gz.length;
  const path = '/' + relative(web, f).split('\\').join('/');
  const hex = [];
  for (let i = 0; i < gz.length; i++) hex.push('0x' + gz[i].toString(16).padStart(2, '0'));
  const lines = [];
  for (let i = 0; i < hex.length; i += 24) lines.push('  ' + hex.slice(i, i + 24).join(','));
  out += `// ${path} (${gz.length} bytes gz)\nstatic const uint8_t WA_${k}[] PROGMEM = {\n${lines.join(',\n')}\n};\n\n`;
  table.push(`  {"${path}", "${MIME[extname(f)]}", WA_${k}, ${gz.length}}`);
  console.log(`${path.padEnd(32)} ${String(gz.length).padStart(8)} B`);
});
out += `static const WebAsset WEB_ASSETS[] = {\n${table.join(',\n')}\n};\nstatic const size_t WEB_ASSET_COUNT = ${table.length};\n`;
writeFileSync(join(root, 'firmware', 'RoboArm', 'web_assets.h'), out);
console.log(`total ${(total / 1024).toFixed(1)} KB gzipped -> firmware/RoboArm/web_assets.h`);
